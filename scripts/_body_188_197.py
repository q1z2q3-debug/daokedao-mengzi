def bower(cx, base, H=78, col=INK, sw=1.0):
    """播种人：头在前低、脊成弧、两腿叉开、一手垂向地。"""
    hy = base - H
    hx, hp = cx + H * 0.30, base - H * 0.44
    o = [C(cx, hy, 5.6, col, sw),
         P(f"M {cx},{hy+5} Q {cx+H*0.14},{base-H*0.66} {hx},{hp}", col, sw * 1.4),
         L(hx, hp, cx + H * 0.16, base, col, sw),
         L(hx, hp, cx + H * 0.44, base, col, sw),
         L(cx + H * 0.07, base - H * 0.72, cx - H * 0.08, base - H * 0.54, col, sw),
         L(cx + H * 0.11, base - H * 0.68, cx + H * 0.26, base - H * 0.12, col, sw)]
    return o


def well(x, y, w=88, hh=58, col=WARM, sw=1.2):
    """井：作「井」字四画，两横两竖，各有出头。"""
    x1, x2 = x + w * 0.34, x + w * 0.66
    y1, y2 = y + hh * 0.32, y + hh * 0.68
    o = [L(x - 5, y1, x + w + 5, y1, col, sw),
         L(x - 5, y2, x + w + 5, y2, col, sw),
         L(x1, y - 6, x1, y + hh + 6, col, sw),
         L(x2, y - 6, x2, y + hh + 6, col, sw)]
    return o


def wave3(x, y, n=3, col=ZONG, sw=1.1, gap=20, ln=56):
    """自口边向右张开的三道声弧（弧心在说话人嘴边）。"""
    o = []
    for i in range(n):
        r = ln * 0.5 + i * gap
        x1, y1 = x + r * math.cos(math.radians(-40)), y + r * math.sin(math.radians(-40))
        x2, y2 = x + r * math.cos(math.radians(40)), y + r * math.sin(math.radians(40))
        o += [P(f"M {x1:.1f},{y1:.1f} A {r:.1f},{r:.1f} 0 0 1 {x2:.1f},{y2:.1f}", col, sw)]
    return o


def tree(x, base, H=150, col=WARM, sw=1.1, wound=0.42):
    """一木：直干、三枝；wound 处一道赭痕，痕上生新枝。"""
    top = base - H
    o = [L(x, base, x, top, col, sw * 1.3),
         L(x - 14, base, x, base - 10, col, sw * 0.9),
         L(x + 14, base, x, base - 10, col, sw * 0.9),
         L(x, top + H * 0.20, x - 34, top + H * 0.04, col, sw),
         L(x, top + H * 0.20, x + 30, top - 2, col, sw),
         L(x, top + H * 0.34, x + 36, top + H * 0.24, col, sw * 0.9),
         L(x, top + H * 0.5, x + 34, top + H * 0.36, col, sw * 0.9),
         L(x, top + H * 0.62, x - 30, top + H * 0.46, col, sw * 0.9)]
    wy = base - H * (1 - wound)
    o += [L(x - 7, wy, x + 7, wy, ZHE, 1.8), L(x - 6, wy + 4, x + 8, wy + 4, ZHE, 1.0)]
    o += [P(f"M {x+5},{wy} C {x+16},{wy-10} {x+20},{wy-18} {x+22},{wy-26}", ZHE, 1.1)]
    o += [C(x + 23, wy - 29, 3.0, ZHE, 0.8)]
    return o


def steprun(x0, base, n=4, w=112, rise=26, col=WARM, sw=1.1):
    """阶梯轮廓：只画折线，不填实（免读作柱状图）。"""
    o = []
    for i in range(n):
        x = x0 + i * w
        y = base - (i + 1) * rise
        o += [L(x, base - i * rise, x, y, col, sw),
              L(x, y, x + w, y, col, sw)]
    o += [L(x0 + n * w, base - n * rise, x0 + n * w, base - (n - 1) * rise, col, sw)]
    return o


def plaque(cx, cy, w=88, hh=92, ch="为", col=WARM, sw=1.2):
    """竖牌，上书一字，一道赭杠划过（禁）。"""
    o = [R(cx - w / 2, cy - hh / 2, w, hh, col, sw, fill=SOFT),
         T(cx, cy + 5, ch, 13, INK, ls=1),
         L(cx - w * 0.40, cy + hh * 0.36, cx + w * 0.40, cy - hh * 0.36, ZHE, 1.4)]
    return o


