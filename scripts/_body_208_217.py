def crown(cx, cy, w=56, col=INK, sw=1.1):
    """冕：横版一块，下三垂旒，旒端各有珠。"""
    o = [R(cx - w / 2, cy, w, 15, col, sw, fill=SOFT),
         L(cx - w / 2, cy + 3, cx + w / 2, cy + 3, ZONG, 0.8)]
    for i in range(3):
        x = cx - w * 0.26 + i * w * 0.26
        o += [L(x, cy + 15, x, cy + 26, col, sw * 0.8), C(x, cy + 29, 1.9, col, sw * 0.6)]
    return o


def seal(cx, cy, w=54, ch="", col=ZONG, sw=1.3):
    """印：方形，上带一小钮，中可嵌一字。"""
    o = [R(cx - w / 2, cy, w, w, col, sw, fill=PALE),
         P(f"M {cx-w*0.14},{cy} L {cx-w*0.10},{cy-8} L {cx+w*0.10},{cy-8} L {cx+w*0.14},{cy}", col, sw)]
    if ch:
        o += [T(cx, cy + w * 0.62, ch, w * 0.30, col)]
    return o


def robe(cx, base, H, col=INK, sw=1.1, fill=SOFT):
    """着袍之人：头、双肩外张、袍身下阔，不见分腿。"""
    hr = max(5, H * 0.075)
    top = base - H
    sh = top + hr * 2 + H * 0.10
    o = [C(cx, top + hr, hr, col, sw),
         L(cx, top + hr * 2, cx, sh, col, sw * 1.2),
         P(f"M {cx-H*0.05},{sh} L {cx-H*0.20},{sh+H*0.14} L {cx-H*0.24},{base} "
           f"L {cx+H*0.24},{base} L {cx+H*0.20},{sh+H*0.14} L {cx+H*0.05},{sh} Z",
           col, sw, fill=fill),
         L(cx - H * 0.12, sh + H * 0.30, cx, base - 2, col, sw * 0.7),
         L(cx + H * 0.12, sh + H * 0.30, cx, base - 2, col, sw * 0.7)]
    return o


def bundle(x, y, w=86, hh=32, col=WARM, sw=1.1):
    """束帛：一捆，中横两道绳。"""
    o = [R(x, y, w, hh, col, sw, fill=SOFT),
         E(x, y + hh * 0.5, 6, hh * 0.5, col, sw * 0.8, fill=SOFT),
         E(x + w, y + hh * 0.5, 6, hh * 0.5, col, sw * 0.8, fill=SOFT),
         L(x + w * 0.3, y, x + w * 0.3, y + hh, ZONG, 0.8),
         L(x + w * 0.66, y, x + w * 0.66, y + hh, ZONG, 0.8)]
    return o


def cloudrain(cx, y, w=70, col=WARM, sw=1.0):
    """云下雨：一段云头、五道雨丝、地下两株苗。"""
    o = [P(f"M {cx-w/2},{y} q 6,-12 18,-8 q 4,-14 18,-8 q 14,-4 16,8 q 2,8 -8,8 L {cx+w/2-14},{y+8}", col, sw, fill=PALE)]
    for i in range(5):
        xx = cx - w * 0.34 + i * w * 0.17
        o += [L(xx, y + 14, xx - 2, y + 30, ZONG, 0.8)]
    return o


def jar(x, base, w=46, hh=50, col=WARM, sw=1.1):
    """陶器：口沿、鼓腹、圈足。"""
    return [E(x + w / 2, base - hh, w / 2, 6, col, sw, fill=SOFT),
            P(f"M {x},{base-hh+4} C {x-4},{base-hh*0.5} {x+6},{base-10} {x+w*0.5},{base-8} "
              f"C {x+w-6},{base-10} {x+w+4},{base-hh*0.5} {x+w},{base-hh+4}", col, sw, fill=SOFT),
            P(f"M {x+w*0.28},{base-8} L {x+w*0.24},{base} L {x+w*0.76},{base} L {x+w*0.72},{base-8}", col, sw * 0.9)]


def shell(cx, cy, r=15, col=ZONG, sw=1.0):
    """贝：扇形，三脊。"""
    o = [P(f"M {cx-r},{cy+6} q {r*0.5},{-r*1.2} {r*2},0", col, sw),
         P(f"M {cx-r},{cy+6} l {r*2},0", col, sw)]
    for i in (-1, 0, 1):
        o += [L(cx, cy + 6, cx + i * r * 0.7, cy - r * 0.5, GREY, 0.7)]
    return o


def qarc(cx, cy, r, col=ZONG, sw=0.9):
    """问答弧：以口为心，向右三道弧。"""
    return [P(f"M {cx+r*0.4},{cy-r*0.5} A {r} {r} 0 0 1 {cx+r*0.4},{cy+r*0.5}", col, sw),
            P(f"M {cx+r*0.8},{cy-r*0.8} A {r*1.4} {r*1.4} 0 0 1 {cx+r*0.8},{cy+r*0.8}", col, sw),
            P(f"M {cx+r*1.2},{cy-r*1.1} A {r*1.8} {r*1.8} 0 0 1 {cx+r*1.2},{cy+r*1.1}", col, sw)]


def road(x1, y1, x2, y2, wid=34, col=WARM, sw=1.0):
    """一条路：两边缘线，中间三道短横。"""
    o = [L(x1, y1 - wid / 2, x2, y2 - wid / 2, col, sw),
         L(x1, y1 + wid / 2, x2, y2 + wid / 2, col, sw)]
    for i in range(3):
        t = (i + 1) / 4.0
        xx = x1 + (x2 - x1) * t
        yy = y1 + (y2 - y1) * t
        o += [L(xx, yy - wid * 0.22, xx, yy + wid * 0.22, GREY, 0.7)]
    return o


