    f = glob.glob('book/MZ%03d-*.md' % n)[0]
    s = open(f, encoding='utf-8').read()
    m = re.search(r'## 十一　存疑\n\n(.*?)\n\n## 十二', s, re.S)
    sec = m.group(1)
    idx = sec.rfind('\n5. **')
    if idx < 0:
        idx = sec.find('5. **')
        head, tail = sec[:idx], sec[idx:]
    else:
        head, tail = sec[:idx + 1], sec[idx + 1:]
    s = s[:m.start(1)] + head + txt + s[m.end(1):]
    open(f, 'w', encoding='utf-8').write(s)

